"""Write LaTeX inputs for the paper from the experiment files, so the paper shows exactly what the agent saw:
  paper/appendix_prompt.tex  the prompt (harness/prompt.md, verbatim, re-wrapped) and the filled catchment description
                             of one catchment (data/agent_inputs/39014/catchment.json)
  paper/listing_runmodel.tex a real run_model call and reply (Ver at Hansteads, repeat 1, default parameters)
"""
import json
import os
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIDTH = 86


def wrap(text):
    out = []
    for para in text.split("\n\n"):
        lines = para.split("\n")
        if para.startswith("#") or para.strip().startswith("{"):
            out.append(para)
        else:
            out.append("\n".join(textwrap.wrap(" ".join(l.strip() for l in lines), WIDTH)))
    return "\n\n".join(out)


prompt = open(os.path.join(ROOT, "harness", "prompt.md"), encoding="utf-8").read().strip()
meta = json.load(open(os.path.join(ROOT, "data", "agent_inputs", "39014", "catchment.json"), encoding="utf-8"))
with open(os.path.join(ROOT, "paper", "appendix_prompt.tex"), "w", encoding="utf-8") as f:
    f.write("% generated by scripts/make_appendix.py from harness/prompt.md and data/agent_inputs/39014/catchment.json\n")
    f.write("The system part of the prompt is sent as the system message and the task part as the first user message. "
            "The placeholders are filled for each run: \\texttt{\\{catchment\\_json\\}} with the catchment description, "
            "\\texttt{\\{max\\_tool\\_calls\\}} with 50 and \\texttt{\\{max\\_runs\\}} with 10000. Line breaks are "
            "adjusted to the page width.\n\n")
    f.write("\\begin{scriptsize}\n\\begin{verbatim}\n" + wrap(prompt) + "\n\\end{verbatim}\n\\end{scriptsize}\n\n")
    f.write("Catchment description given in place of \\texttt{\\{catchment\\_json\\}} for the Ver at Hansteads "
            "(39014). Climate indices are computed from the calibration period only.\n\n")
    js = json.dumps(meta, indent=1, ensure_ascii=False)
    f.write("\\begin{scriptsize}\n\\begin{verbatim}\n" + js + "\n\\end{verbatim}\n\\end{scriptsize}\n")

for line in open(os.path.join(ROOT, "runs", "agents", "claude-api", "39014", "r1", "transcript.jsonl"), encoding="utf-8"):
    d = json.loads(line)
    if d["kind"] == "tool" and d["name"] == "run_model":
        call, reply = d["args"], json.loads(d["result"])
        break
stores = "\n".join(f'    "{k}": {json.dumps(v)},' for k, v in reply["stores"].items()).rstrip(",")
pm = reply["performance_metrics"]
txt = (f'call:  run_model({json.dumps(call)})\n'
       f'reply: {{"model_id": "{reply["model_id"]}", "n_timesteps": {reply["n_timesteps"]},\n'
       f'  "mean_discharge": {reply["mean_discharge"]}, "max_discharge": {reply["max_discharge"]},\n'
       f'  "performance_metrics": {{"NSE": {pm["NSE"]}, "KGE": {pm["KGE"]},\n'
       f'                          "PBIAS": {pm["PBIAS"]}, "r": {pm["r"]}, ...}},\n'
       f'  "stores": {{\n{stores}}}}}')
with open(os.path.join(ROOT, "paper", "listing_runmodel.tex"), "w", encoding="utf-8") as f:
    f.write("% generated by scripts/make_appendix.py from runs/agents/claude-api/39014/r1/transcript.jsonl\n")
    f.write("\\begin{footnotesize}\n\\begin{verbatim}\n" + txt + "\n\\end{verbatim}\n\\end{footnotesize}\n")
print("wrote paper/appendix_prompt.tex and paper/listing_runmodel.tex")
